// Offline generator: keep iconify_flutter 0.0.7 field order, use official bodies.
// 离线生成器：保留 iconify_flutter 0.0.7 字段顺序，改用官方 SVG 内容。
// Run from bench_app with four local JSON paths; no network access is used.
// 在 bench_app 下传入四个本地 JSON 路径；脚本不联网。
// dart run tool/gen_anim_icons.dart <line-md-icons.json> <eos-icons-icons.json>
//   <line-md-info.json> <eos-icons-info.json>
import 'dart:convert';
import 'dart:io';

const _rosterVersion = '0.0.7';
const _lineMdVersion = '1.2.16';
const _eosIconsVersion = '1.2.4';
const _outputPath = 'lib/anim_icons_real.dart';
const _parentKey = 'parent';
const _infoKey = 'info';
const _prefixKey = 'prefix';
const _urlKey = 'url';
const _fieldSeparator = '_';
const _legacyAnimationTag = '<animate';
const _maskTag = '<mask';
const _loopMarker = 'indefinite';
const _none = 'none / 无';
const _missing = 'Name not found / 官方名称不存在';
const _invalidName = 'Invalid name mapping / 名称转换失败';
const _transformedAlias = 'Alias has transforms / 别名带变换';
const _invalidAlias = 'Invalid or cyclic alias / 别名无效或循环';
const _staticIcon = 'No official SMIL animation / 官方已无 SMIL 动画';
const _skipReasons = [
  _invalidName,
  _missing,
  _transformedAlias,
  _invalidAlias,
  _staticIcon,
];
const _geometryDefaults = {'width': 16, 'height': 16, 'left': 0, 'top': 0};
const _transformKeys = ['rotate', 'hFlip', 'vFlip'];
const _collections = [
  (
    prefix: 'line-md',
    version: _lineMdVersion,
    source: 'line_md',
    rosterCount: 389,
  ),
  (
    prefix: 'eos-icons',
    version: _eosIconsVersion,
    source: 'eos_icons',
    rosterCount: 10,
  ),
];
final _fieldPattern = RegExp(
  r"static const String (\w+) =\s*'((?:[^'\\]|\\.)*)';",
  dotAll: true,
);
final _smilTag = RegExp(r'<(?:animate(?:Transform|Motion)?|set)(?=[\s/>])');
final _animationTag = RegExp(r'<(?:animate(?:Transform|Motion)?|set)\b[^>]*>');
final _toAttribute = RegExp(r'\s+to\s*=');
final _startAttribute = RegExp(r'\s+(?:values|from)\s*=');
final _unfilledGroup = RegExp(r'''<g\b[^>]*\sfill\s*=\s*["']none["']''');
final _acronymBoundary = RegExp(r'([A-Z]+)([A-Z][a-z])');
final _camelBoundary = RegExp(r'([a-z0-9])([A-Z])');
final _officialNamePattern = RegExp(r'^[a-z0-9]+(?:-[a-z0-9]+)*$');

// Keep digits: iconify1 is an official name, not an escaped identifier.
// Accept snake_case (the cached package), camelCase and a reserved-word suffix.
// 保留数字：iconify1 就是官方名称；兼容下划线、驼峰和保留字尾下划线。
String? _officialName(String field) {
  final unescaped = field.endsWith(_fieldSeparator)
      ? field.substring(0, field.length - 1)
      : field;
  final name = unescaped
      .replaceAllMapped(_acronymBoundary, (m) => '${m[1]}-${m[2]}')
      .replaceAllMapped(_camelBoundary, (m) => '${m[1]}-${m[2]}')
      .replaceAll(_fieldSeparator, '-')
      .toLowerCase();
  return _officialNamePattern.hasMatch(name) ? name : null;
}

Map<String, dynamic> _readJson(String path) =>
    jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;

// Inherit geometry through parent chains; skip aliases declaring transforms.
// 沿 parent 链继承尺寸；声明 rotate/hFlip/vFlip 的别名直接跳过。
Map<String, dynamic> _resolveIcon(
  String name,
  Map<String, dynamic> icons,
  Map<String, dynamic> aliases, [
  Set<String>? visited,
]) {
  final seen = visited ?? <String>{};
  if (!seen.add(name)) throw _Skip(_invalidAlias);
  final icon = icons[name] as Map<String, dynamic>?;
  if (icon != null) return icon;
  final alias = aliases[name] as Map<String, dynamic>?;
  if (alias == null) throw _Skip(seen.length == 1 ? _missing : _invalidAlias);
  if (_transformKeys.any(alias.containsKey)) throw _Skip(_transformedAlias);
  final parent = alias[_parentKey];
  if (parent is! String) throw _Skip(_invalidAlias);
  return {..._resolveIcon(parent, icons, aliases, seen), ...alias}
    ..remove(_parentKey);
}

class _Skip implements Exception {
  const _Skip(this.reason);
  final String reason;
}

void main(List<String> args) {
  try {
    _generate(args);
  } on Object catch (error) {
    stderr.writeln('Generation failed / 生成失败: $error');
    exitCode = 1;
  }
}

void _generate(List<String> args) {
  if (args.length != _collections.length * 2) {
    throw ArgumentError(
      'Expected icons JSON paths (line-md, eos-icons), then '
      'their info JSON paths / 依次传入两个图标 JSON 和对应两个 info JSON 路径',
    );
  }
  final pubCache =
      Platform.environment['PUB_CACHE'] ??
      '${Platform.environment['LOCALAPPDATA']}/Pub/Cache';
  final package = '$pubCache/hosted/pub.dev/iconify_flutter-$_rosterVersion';
  final output = StringBuffer()
    ..writeln('// GENERATED by tool/gen_anim_icons.dart. Do not edit by hand.')
    ..writeln('// 由 tool/gen_anim_icons.dart 生成，请勿手改。')
    ..writeln(
      '// Roster only / 仅名单: iconify_flutter $_rosterVersion; '
      'LineMd, EosIcons; declaration order / 声明顺序。',
    )
    ..writeln('// Official SVG data and licensing / 官方 SVG 数据与许可:');
  final svgs = <String>[];
  final skips = {for (final reason in _skipReasons) reason: <String>[]};
  var rosterTotal = 0;
  var resolvedAliases = 0;
  for (var index = 0; index < _collections.length; index++) {
    final collection = _collections[index];
    final data = _readJson(args[index]);
    final metadata = _readJson(args[index + _collections.length]);
    final info =
        (data[_infoKey] ?? metadata[_infoKey] ?? metadata)
            as Map<String, dynamic>;
    if (data[_prefixKey] != collection.prefix ||
        info[_prefixKey] != collection.prefix) {
      throw FormatException('Collection prefix mismatch / 集合前缀不匹配');
    }
    final author = info['author'] as Map<String, dynamic>;
    final license = info['license'] as Map<String, dynamic>;
    if (license['spdx'] != 'MIT') {
      throw FormatException('Expected MIT license / 应为 MIT 许可');
    }
    output
      ..writeln(
        '// @iconify-json/${collection.prefix}@${collection.version}; '
        'license / 许可: ${license['title']} (${license[_urlKey]})',
      )
      ..writeln(
        '// Author and source / 作者及来源: '
        '${author['name']}; ${author[_urlKey]}',
      )
      ..writeln(
        '// JSON: https://unpkg.com/@iconify-json/'
        '${collection.prefix}@${collection.version}/icons.json',
      );
    final source = File('$package/lib/icons/${collection.source}.dart')
        .readAsStringSync();
    final roster = _fieldPattern
        .allMatches(source)
        .where((m) => m[2]!.contains(_legacyAnimationTag))
        .toList();
    if (roster.length != collection.rosterCount) {
      throw StateError(
        'Roster changed / 名单发生变化: ${collection.prefix}; '
        '${roster.length} != ${collection.rosterCount}',
      );
    }
    rosterTotal += roster.length;
    final icons = data['icons'] as Map<String, dynamic>;
    final aliases = data['aliases'] as Map<String, dynamic>? ?? {};
    final before = svgs.length;
    for (final field in roster) {
      final fieldName = field[1]!;
      final name = _officialName(fieldName);
      final label = '${collection.prefix}:$fieldName -> ${name ?? _none}';
      try {
        if (name == null) throw _Skip(_invalidName);
        final icon = _resolveIcon(name, icons, aliases);
        final body = icon['body'] as String;
        if (!_smilTag.hasMatch(body)) throw _Skip(_staticIcon);
        final geometry = {
          for (final entry in _geometryDefaults.entries)
            entry.key: icon[entry.key] ?? data[entry.key] ?? entry.value,
        };
        final [width, height, left, top] = geometry.values.toList();
        svgs.add(
          '<svg xmlns="http://www.w3.org/2000/svg" '
          'width="$width" height="$height" '
          'viewBox="$left $top $width $height">$body</svg>',
        );
        if (aliases.containsKey(name)) resolvedAliases++;
      } on _Skip catch (skip) {
        skips[skip.reason]!.add(label);
      }
    }
    stderr.writeln(
      '${collection.prefix}@${collection.version}: '
      'roster / 名单=${roster.length}, kept / 保留=${svgs.length - before}',
    );
  }
  if (svgs.isEmpty) throw StateError('No animated icons / 没有动画图标');
  final skipped = skips.values.fold(0, (sum, names) => sum + names.length);
  output
    ..writeln('// Run from benchmark/bench_app / 在 benchmark/bench_app 执行:')
    ..writeln(
      '// dart run tool/gen_anim_icons.dart <line-md-icons.json> '
      '<eos-icons-icons.json> <line-md-info.json> <eos-icons-info.json>',
    )
    ..writeln(
      '// Inputs must match the pinned npm versions above. '
      '/ 输入文件须匹配上述固定 npm 版本。',
    )
    ..writeln(
      '// Aliases / 别名: parent chain and geometry inherited; '
      'rotate/hFlip/vFlip declarations skipped / 继承父链和尺寸，带变换则跳过。',
    )
    ..writeln(
      '// Roster / 名单: $rosterTotal; kept / 保留: ${svgs.length}; '
      'skipped / 跳过: $skipped; resolved aliases / 已解析别名: $resolvedAliases.',
    );
  for (final reason in _skipReasons) {
    final names = skips[reason]!;
    final summary =
        '$reason (${names.length}): '
        '${names.isEmpty ? _none : names.join(', ')}';
    output.writeln('// $summary');
    stderr.writeln(summary);
  }
  output.writeln('const List<String> animIconsReal = <String>[');
  for (final svg in svgs) {
    // JSON escaping is Dart-compatible after escaping interpolation markers.
    // JSON 转义兼容 Dart；另行转义插值标记，保持原始 SVG 内容。
    output.writeln('  ${jsonEncode(svg).replaceAll(r'$', r'\$')},');
  }
  output.writeln('];');
  final file = File(_outputPath)..writeAsStringSync(output.toString());
  final masked = svgs.where((svg) => svg.contains(_maskTag)).length;
  final looping = svgs.where((svg) => svg.contains(_loopMarker));
  final loopingMasked = looping.where((svg) => svg.contains(_maskTag)).length;
  final unfilledGroups = svgs.fold(
    0,
    (count, svg) => count + _unfilledGroup.allMatches(svg).length,
  );
  final toOnly = svgs
      .expand(_animationTag.allMatches)
      .where(
        (tag) =>
            _toAttribute.hasMatch(tag[0]!) &&
            !_startAttribute.hasMatch(tag[0]!),
      )
      .length;
  stderr
    ..writeln(
      'Wrote / 已写入: ${svgs.length}/$rosterTotal; skipped / 跳过: '
      '$skipped; bytes / 字节: ${file.lengthSync()}; $_outputPath',
    )
    ..writeln(
      'Masked icons / 含 mask 图标: $masked; fill="none" groups / 分组: '
      '$unfilledGroups; to-only SMIL elements / 动画元素: $toOnly',
    )
    ..writeln(
      'one_anim looping plain / 无 mask 循环: '
      '${looping.length - loopingMasked}; masked / 有 mask 循环: $loopingMasked',
    );
}
