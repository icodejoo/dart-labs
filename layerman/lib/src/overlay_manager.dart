/// Condition predicate; receives the manager's context map (see
/// [Layerman.setContext]). When provided it is the SOLE authority —
/// `route` / `requiresAuth` sugar is ignored (TS parity).
typedef OverlayPredicate = bool Function(Map<String, Object?> context);

/// Frequency-capping configuration. All present fields must pass (AND), and
/// counts increment when the overlay actually opens (TS parity).
///
/// * [session] — at most N times per manager instance (in memory).
/// * [total] — at most N times ever (persisted).
/// * [day]/[hour]/[minute] — at most N times per LOCAL calendar day/hour/minute
///   (persisted).
/// * [minGap] — a rolling minimum interval since the last open (persisted).
class OverlayCooldown {
  const OverlayCooldown({
    this.session,
    this.total,
    this.day,
    this.hour,
    this.minute,
    this.minGap,
  });

  final int? session;
  final int? total;
  final int? day;
  final int? hour;
  final int? minute;
  final Duration? minGap;

  bool get _needsPersistence =>
      total != null ||
      day != null ||
      hour != null ||
      minute != null ||
      minGap != null;
}

/// Pluggable persistence for [OverlayCooldown] counters. The default is
/// [MemoryCooldownStorage]; back it with `shared_preferences` (or anything
/// else) in real apps:
///
/// ```dart
/// class PrefsCooldownStorage implements OverlayCooldownStorage {
///   Future<String?> read(String key) async =>
///       (await SharedPreferences.getInstance()).getString(key);
///   Future<void> write(String key, String value) async =>
///       (await SharedPreferences.getInstance()).setString(key, value);
/// }
/// ```
abstract class OverlayCooldownStorage {
  Future<String?> read(String key);
  Future<void> write(String key, String value);
}

/// In-memory [OverlayCooldownStorage] (per-process; survives manager
/// re-creation when the same instance is shared).
class MemoryCooldownStorage implements OverlayCooldownStorage {
  final Map<String, String> _store = <String, String>{};

  @override
  Future<String?> read(String key) async => _store[key];

  @override
  Future<void> write(String key, String value) async => _store[key] = value;
}

/// A lightweight view of one managed entry, handed to [Layerman.clearWhere].
class OverlayRecord {
  const OverlayRecord._(
      this.id, this.slot, this.data, this.active, this.phase, this.tags);

  final String id;
  final String slot;
  final Object? data;

  /// Whether the entry currently occupies a slot / overlaps (vs queued).
  final bool active;

  /// `pending` / `resolving` / `open` / `closing`.
  final String phase;

  /// 提交时复制的只读标签集合，默认空集合。
  final Set<String> tags;
}

/// Context handed to a [Present] callback when the queue grants permission to
/// show an overlay.
class PresentContext {
  const PresentContext._(this.id, this.slot, this.data, this.dataListenable);

  /// Unique id of the queue entry (same as the id passed to / generated by
  /// [Layerman.open]).
  final String id;

  /// The serial slot this entry was queued in.
  final String slot;

  /// Opaque payload handed to [Layerman.open] (post-`resolve` if any).
  final Object? data;

  /// 实时数据通道；update 和 resolve 更新时通知，data 仍为展示时快照。
  final ValueListenable<Object?> dataListenable;
}

/// Bidirectional handle returned by a [Present] callback.
///
/// Adapts a UI backend (showDialog / GetX / bot_toast / a self-managed
/// `OverlayEntry` / ...) to the orchestrator:
///
/// * [dismissed] — the backend's completion signal. It must complete when the
///   overlay is closed **through any path** (user tap, barrier, back button,
///   timeout, programmatic close). Its value becomes the result of
///   [Layerman.open].
/// * [dismiss] — lets the orchestrator close the backend (replace/preemption/
///   [Layerman.close]). Must target **this** overlay specifically (e.g.
///   pop by unique route name, `SnackbarController.close()`, `CancelFunc`) —
///   never "pop whatever is on top".
class PresentedOverlay<T> {
  PresentedOverlay({required this.dismissed, this.dismiss});

  /// Completes when the backend overlay is fully closed.
  final Future<T?> dismissed;

  /// Gracefully close the backend overlay, optionally delivering [result].
  /// When null the orchestrator cannot preempt this overlay; [Layerman.close]
  /// then only detaches it from the queue (the backend keeps its own lifecycle).
  final Future<void> Function([T? result])? dismiss;
}

/// Presents an overlay through a UI backend when the queue grants permission.
/// Called at most once per queue entry.
///
/// This is the SOLE rendering hook: the callback shows the UI however it likes
/// (it may push a route, call `Get.dialog`, fire `BotToast.show`, insert an
/// `OverlayEntry` the caller owns, ...) and returns a [PresentedOverlay] so the
/// orchestrator can await its close and preempt it. The manager itself never
/// touches the widget tree — it is UI-agnostic.
typedef Present<T> = PresentedOverlay<T> Function(PresentContext context);

/// 单次提交的类型化句柄；同 id 重开后，旧票的操作静默失效。
class OverlayTicket<T> {
  OverlayTicket._(this._manager, this._entry, this._result, this._outcome)
      : id = _entry.id,
        slot = _entry.slot;

  /// 拥有此次提交的管理器。
  final Layerman _manager;

  /// 此票唯一绑定的条目身份。
  final _Entry _entry;

  /// 兼容 open 的结果通道。
  final Future<T?> _result;

  /// 携带首次结束原因的结果通道。
  final Future<OverlayOutcome<T>> _outcome;

  /// 此次提交的标识。
  final String id;

  /// 此次提交所属槽位。
  final String slot;

  /// 结束时返回结果；未出场或无结果时为 null。
  Future<T?> get result => _result;

  /// 首次结束时的结果与原因。
  Future<OverlayOutcome<T>> get outcome => _outcome;

  /// 此条目是否仍被管理器跟踪，包含排队和退场阶段。
  bool get isActive => !_manager.isDisposed && _manager._isCurrent(_entry);

  /// 以类型化的 [result] 请求关闭；遵守 beforeClose 守卫。
  void close([T? result]) {
    if (isActive) _manager._batch(() => _manager._close(_entry, result));
  }

  /// 立即移除此条目，绕过关闭守卫。
  void remove() {
    if (isActive) _manager._batch(() => _manager._remove(_entry));
  }

  /// 更新此条目数据；Map 浅合并，其余值替换。
  void update(Object? patch) {
    if (isActive) _manager.update(id, patch);
  }

  /// 此条目的实时数据通道，结束后仍可读取最后的数据。
  ValueListenable<Object?> get data => _entry.dataNotifier;
}

/// 独立的暂停来源；释放幂等，不会覆盖其他暂停来源。
class OverlayHold {
  OverlayHold._(this.reason, this._release);

  /// 调用方提供的暂停原因，仅用于描述。
  final Object? reason;

  /// 释放回调；清空即表示已释放。
  VoidCallback? _release;

  /// 是否已经释放，管理器销毁后也为 true。
  bool get isReleased => _release == null;

  /// 释放此次暂停；重复调用或管理器销毁后无操作。
  void release() {
    final callback = _release;
    _release = null;
    callback?.call();
  }
}

enum _EntryPhase { pending, resolving, open, closing }

/// Internal, generic-erased queue/active record.
class _Entry {
  _Entry({
    required this.id,
    required this.slot,
    required this.tags,
    required this.priority,
    required this.seq,
    required this.replace,
    required this.affix,
    required this.delay,
    required this.duration,
    required this.exitDuration,
    required this.when,
    required this.route,
    required this.requiresAuth,
    required this.dismissWhenUnmet,
    required this.cooldown,
    required this.beforeClose,
    required this.resolveData,
    required this.presentBackend,
    required this.settle,
    required this.settleOutcome,
    required this.acceptsResult,
    required Object? data,
    required this.resolveTimeout,
  }) : dataNotifier = ValueNotifier<Object?>(data);

  final String id;
  final String slot;

  /// 提交时复制的标签，调用方后续修改不影响条目。
  final Set<String> tags;

  final int priority;
  final int seq;
  final bool replace;
  final bool affix;
  final Duration? delay;
  final Duration? duration;
  final Duration? exitDuration;

  final OverlayPredicate? when;
  final Object? route;
  final bool? requiresAuth;
  final bool dismissWhenUnmet;
  final OverlayCooldown? cooldown;
  final FutureOr<bool> Function()? beforeClose;

  /// Backend-driven data resolution (generic-erased); null skips the overlay.
  final Future<Object?> Function()? resolveData;

  /// Invokes the user's [Present] callback and wires the returned handle
  /// (generic-erased). Called once, when the queue grants this entry its slot.
  final void Function() presentBackend;

  /// Graceful backend close, wired by [presentBackend] once presented.
  Future<void> Function(Object? result)? externalDismiss;

  /// Whether the backend reported (or was told) it is fully closed.
  bool externalDone = false;

  /// 是否已经请求过后端 dismiss；每个条目最多请求一次，避免 close 之后
  /// 又因 remove / clear / dismiss 超时再请求一次（对 popUntil、Get.back()
  /// 这类非幂等后端会误关别的弹窗）。
  bool dismissRequested = false;

  /// Complete the result future exactly once (typed cast lives in the closure).
  final void Function(Object? result) settle;

  /// 完成类型化的结束结果。
  final void Function(Object? result, OverlayEndReason reason) settleOutcome;

  /// 第一次结束原因，后续关闭回调不能覆盖。
  OverlayEndReason? endReason;

  /// 尚未激活的串行条目过期计时器。
  Timer? queueTimer;

  /// 实时数据通知器；退场动画可能继续监听，不主动 dispose，由 GC 回收。
  final ValueNotifier<Object?> dataNotifier;

  /// 当前数据，写入时同步通知后端。
  Object? get data => dataNotifier.value;

  /// 写入新数据并通知实时通道的监听者。
  set data(Object? value) => dataNotifier.value = value;

  /// 此条目解析的最长等待时间；null 表示不限时。
  final Duration? resolveTimeout;

  /// 等待后端完成关闭的兜底计时器。
  Timer? dismissTimer;

  /// 等待解析完成的兜底计时器。
  Timer? resolveTimer;

  /// 条目离开或解析结束时取消兜底计时器。
  void cancelTimeouts() {
    queueTimer?.cancel();
    queueTimer = null;
    dismissTimer?.cancel();
    dismissTimer = null;
    resolveTimer?.cancel();
    resolveTimer = null;
  }

  _EntryPhase phase = _EntryPhase.pending;
  bool skipGap = false;
  bool delayConsumed = false;

  /// 校验擦除泛型后的关闭结果。
  final bool Function(Object? result) acceptsResult;

  /// 防止异步关闭守卫重复执行。
  bool closeGuardPending = false;

  /// 每个条目的条件异常最多上报一次。
  bool conditionErrorReported = false;

  bool settled = false;
  bool paused = false;

  /// Resolved payload parked while the manager is paused.
  bool hasHeldData = false;

  Timer? durationTimer;
  DateTime? durationDeadline;
  Duration? durationRemaining;
  Timer? removeTimer;

  bool get isActive =>
      phase == _EntryPhase.open ||
      phase == _EntryPhase.closing ||
      phase == _EntryPhase.resolving;

  bool get isShown => phase == _EntryPhase.open || phase == _EntryPhase.closing;
}

