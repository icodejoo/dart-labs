/// 统一上报引擎与存储异常，保留操作上下文。
void _reportError(Object error, StackTrace stack, String what) {
  FlutterError.reportError(FlutterErrorDetails(
    exception: error,
    stack: stack,
    library: 'layerman',
    context: ErrorDescription(what),
  ));
}

String _two(int n) => n < 10 ? '0$n' : '$n';
String _dayBucketOf(DateTime t) => '${t.year}-${_two(t.month)}-${_two(t.day)}';
String _hourBucketOf(DateTime t) => '${_dayBucketOf(t)}T${_two(t.hour)}';
String _minuteBucketOf(DateTime t) => '${_hourBucketOf(t)}:${_two(t.minute)}';

/// Hydrate-once cooldown store: reads run synchronously after [hydrate];
/// writes are fire-and-forget write-through.
class _CooldownStore {
  _CooldownStore(this._storage, this._key);

  final OverlayCooldownStorage _storage;
  final String _key;
  final Map<String, _CooldownRecord> _persisted = <String, _CooldownRecord>{};
  final Map<String, int> _session = <String, int>{};

  /// 读取成功或失败后均允许调度继续。
  bool _hydrated = false;

  /// 等待落盘的最新快照是否有变化。
  bool _dirty = false;

  /// 保证同一存储最多只有一次写入在途。
  bool _writing = false;

  /// hydrate 前的重置墓碑，防止旧存储记录重新进入内存。
  final _resetIds = <String>{};

  /// hydrate 前是否已请求清空全部记录。
  bool _resetAll = false;

  /// 清除指定 id 或全部计数，并串行写回最新快照。
  void reset([String? id]) {
    if (id == null) {
      _session.clear();
      _persisted.clear();
      if (!_hydrated) _resetAll = true;
    } else {
      _session.remove(id);
      _persisted.remove(id);
      if (!_hydrated) _resetIds.add(id);
    }
    _flush();
  }

  /// 读取持久化计数并与内存中可能已有的记录合并。
  Future<void> hydrate() async {
    try {
      final raw = await _storage.read(_key);
      if (raw != null) {
        final decoded = jsonDecode(raw) as Map<String, Object?>;
        for (final entry in decoded.entries) {
          if (_resetAll || _resetIds.contains(entry.key)) continue;
          final value = entry.value;
          if (value is Map) {
            final incoming =
                _CooldownRecord.fromJson(value.cast<String, Object?>());
            final current = _persisted[entry.key];
            _persisted[entry.key] =
                current == null ? incoming : _merge(current, incoming);
          }
        }
      }
    } catch (error, stack) {
      _reportError(error, stack, 'while hydrating cooldown storage "$_key"');
    } finally {
      _hydrated = true;
      _resetIds.clear();
      _resetAll = false;
      if (_dirty) _flush();
    }
  }

  /// 合并累计次数、最新时间桶和最近展示时间。
  _CooldownRecord _merge(_CooldownRecord a, _CooldownRecord b) {
    int count(String ab, int ac, String bb, int bc) =>
        ab == bb ? ac + bc : (ab.compareTo(bb) > 0 ? ac : bc);
    String bucket(String a, String b) => a.compareTo(b) >= 0 ? a : b;
    final al = a.lastShownMs;
    final bl = b.lastShownMs;
    return _CooldownRecord(
      total: a.total + b.total,
      dayBucket: bucket(a.dayBucket, b.dayBucket),
      dayCount: count(a.dayBucket, a.dayCount, b.dayBucket, b.dayCount),
      hourBucket: bucket(a.hourBucket, b.hourBucket),
      hourCount: count(a.hourBucket, a.hourCount, b.hourBucket, b.hourCount),
      minuteBucket: bucket(a.minuteBucket, b.minuteBucket),
      minuteCount:
          count(a.minuteBucket, a.minuteCount, b.minuteBucket, b.minuteCount),
      lastShownMs: al == null ? bl : (bl == null || al > bl ? al : bl),
    );
  }

  /// 直接调用存储写入；读取或写入未决时只保留脏位。
  void _flush() {
    _dirty = true;
    if (!_hydrated || _writing) return;
    _dirty = false;
    _writing = true;
    final json = <String, Object?>{
      for (final e in _persisted.entries) e.key: e.value.toJson(),
    };
    void onWriteError(Object error, StackTrace stack) {
      _reportError(error, stack,
          'while writing cooldown storage "$_key" (ids: ${json.keys.join(', ')})');
      _finishWrite();
    }

    try {
      _storage.write(_key, jsonEncode(json)).then(
            (_) => _finishWrite(),
            onError: onWriteError,
          );
    } catch (error, stack) {
      onWriteError(error, stack);
    }
  }

  /// 在途写入结束后补写最新快照。
  void _finishWrite() {
    _writing = false;
    if (_dirty) _flush();
  }

  /// session 耗尽立即永久受阻；total 必须读取完成后才能判定。
  bool permanentlyBlocked(String id, OverlayCooldown cd) =>
      (cd.session != null && (_session[id] ?? 0) >= cd.session!) ||
      (_hydrated &&
          cd.total != null &&
          (_persisted[id]?.total ?? 0) >= cd.total!);

  // Equivalent to `timeUntilEligible(...) == Duration.zero`: only zero passes.
  bool canShow(String id, OverlayCooldown cd, DateTime now) =>
      timeUntilEligible(id, cd, now) == Duration.zero;

  /// How long until [id] could next pass [cd] on its **time-based** caps
  /// (`minGap` + day/hour/minute bucket rollover), or `null` if a cap that
  /// never auto-clears (`session`/`total`) currently blocks it. `Duration.zero`
  /// means the cooldown already passes (any remaining block is not time-based).
  /// Used to wake a queued entry exactly when its cooldown expires.
  Duration? timeUntilEligible(String id, OverlayCooldown cd, DateTime now) {
    if (!_hydrated && cd._needsPersistence) return null;
    if (cd.session != null && (_session[id] ?? 0) >= cd.session!) return null;
    final rec = _persisted[id];
    if (cd.total != null && (rec?.total ?? 0) >= cd.total!) return null;
    var wait = Duration.zero;
    void bump(Duration d) {
      if (d > wait) wait = d;
    }

    if (cd.day != null) {
      final c =
          rec != null && rec.dayBucket == _dayBucketOf(now) ? rec.dayCount : 0;
      if (c >= cd.day!) {
        final next = DateTime(now.year, now.month, now.day + 1);
        bump(next.difference(now));
      }
    }
    if (cd.hour != null) {
      final c = rec != null && rec.hourBucket == _hourBucketOf(now)
          ? rec.hourCount
          : 0;
      if (c >= cd.hour!) {
        final next = DateTime(now.year, now.month, now.day, now.hour + 1);
        bump(next.difference(now));
      }
    }
    if (cd.minute != null) {
      final c = rec != null && rec.minuteBucket == _minuteBucketOf(now)
          ? rec.minuteCount
          : 0;
      if (c >= cd.minute!) {
        final next =
            DateTime(now.year, now.month, now.day, now.hour, now.minute + 1);
        bump(next.difference(now));
      }
    }
    if (cd.minGap != null && rec?.lastShownMs != null) {
      final remain = cd.minGap!.inMilliseconds -
          (now.millisecondsSinceEpoch - rec!.lastShownMs!);
      if (remain > 0) bump(Duration(milliseconds: remain));
    }
    return wait;
  }

  void record(String id, OverlayCooldown cd, DateTime now) {
    if (cd.session != null) _session[id] = (_session[id] ?? 0) + 1;
    if (!cd._needsPersistence) return;
    final rec = _persisted.putIfAbsent(id, _CooldownRecord.new);
    rec.total += 1;
    final dayB = _dayBucketOf(now);
    rec.dayCount = rec.dayBucket == dayB ? rec.dayCount + 1 : 1;
    rec.dayBucket = dayB;
    final hourB = _hourBucketOf(now);
    rec.hourCount = rec.hourBucket == hourB ? rec.hourCount + 1 : 1;
    rec.hourBucket = hourB;
    final minB = _minuteBucketOf(now);
    rec.minuteCount = rec.minuteBucket == minB ? rec.minuteCount + 1 : 1;
    rec.minuteBucket = minB;
    rec.lastShownMs = now.millisecondsSinceEpoch;
    _flush();
  }
}

/// A **headless** overlay **queue** orchestrator.
///
/// The manager owns scheduling, not rendering: it never inserts widgets or
/// touches the widget tree. Every overlay is shown through a [Present] backend
/// (showDialog / GetX / bot_toast / a self-managed `OverlayEntry` / ...) that
/// the manager invokes when the queue grants a slot, and closes through the
/// [PresentedOverlay] handle the backend returns. This keeps the core
/// UI-agnostic and mirrors the headless TS sister package. It provides:
///
/// * **serial one-at-a-time** queueing per named [slot] (default slot `''`),
///   with an optional [gap] between successive overlays;
/// * **priority** (higher shows first; FIFO within a priority);
/// * **replace** (preempt the current overlay of a slot), **affix** (protect
///   the current overlay from `replace`) and **overlap** (bypass the queue and
///   stack immediately);
/// * **conditions** (`when` / `route` / `requiresAuth` against [setContext],
///   with `dismissWhenUnmet` auto-dismissal) and **cooldown** frequency caps;
/// * backend-driven **`resolve`** data loading and a **`beforeClose`** guard;
/// * imperative **`Future<T?>` results** (like `showDialog`);
/// * **two-phase close** (a per-entry `exitDuration` grace + the backend's own
///   `dismissed` signal) so a backend can play its exit animation before the
///   queue advances;
/// * **pauseAll/resumeAll** full freeze and per-id **pause/resume** for
///   `duration` timers.
class Layerman extends ChangeNotifier {
  Layerman({
    this.gap = Duration.zero,
    Map<String, OverlaySlotOptions> slots = const {},
    this.dismissTimeout = const Duration(seconds: 10),
    this.resolveTimeout = const Duration(seconds: 30),
    OverlayCooldownStorage? cooldownStorage,
    String storageKey = 'layerman:cooldown',
    DateTime Function()? now,
    List<Object> pauseOnRoutes = const <Object>[],
  })  : assert(slots.values.every(
            (options) => options.maxQueued == null || options.maxQueued! > 0)),
        slots = Map<String, OverlaySlotOptions>.unmodifiable(slots),
        assert(
          pauseOnRoutes.every(_isRoutePattern),
          'each pauseOnRoutes pattern must be a String, List<String> or RegExp',
        ),
        _pauseOnRoutes = pauseOnRoutes,
        _now = now ?? DateTime.now {
    _cooldowns =
        _CooldownStore(cooldownStorage ?? MemoryCooldownStorage(), storageKey);
    _ready = _cooldowns.hydrate().then((_) => _batch(() {
          if (isDisposed) return;
          if (!_paused) {
            _applyRelease();
          } else {
            _notify();
          }
        }));
  }

  /// 当前是否处于构建帧；纯 Dart/headless 未初始化绑定时 instance 会抛出。
  bool get _inBuildPhase {
    try {
      return SchedulerBinding.instance.schedulerPhase ==
          SchedulerPhase.persistentCallbacks;
    } catch (_) {
      return false;
    }
  }

  /// 公开操作与异步状态变化的嵌套批次深度。
  int _batchDepth = 0;

  /// 当前批次是否需要通知。
  bool _notifyPending = false;

  /// 是否已经登记帧后通知。
  bool _frameNotifyPending = false;

  /// 本帧已登记调度的槽位。
  final _deferredSlots = <String>{};

  /// 是否已经登记帧后释放。
  bool _releasePending = false;

  /// 原子完成一组同步状态变化，最外层结束后回收槽位并统一通知。
  R _batch<R>(R Function() action) {
    _batchDepth++;
    try {
      return action();
    } finally {
      _batchDepth--;
      if (_batchDepth == 0) {
        _slots.removeWhere((_, s) =>
            s.active == null &&
            s.queue.isEmpty &&
            s.gapTimer == null &&
            s.delayTimer == null &&
            s.cooldownTimer == null &&
            !s.gapPending);
        if (_notifyPending) {
          _notifyPending = false;
          _notify();
        }
      }
    }
  }

  /// 合并批次内通知；构建中统一延至帧后，销毁后静默忽略。
  void _notify() {
    if (isDisposed) return;
    if (_batchDepth > 0) {
      _notifyPending = true;
      return;
    }
    if (_inBuildPhase) {
      if (_frameNotifyPending) return;
      _frameNotifyPending = true;
      SchedulerBinding.instance.addPostFrameCallback((_) {
        if (!_frameNotifyPending) return;
        _frameNotifyPending = false;
        if (!isDisposed) _notify();
      });
      return;
    }
    // 帧后展示产生的通知同时覆盖本帧已登记的通知。
    _frameNotifyPending = false;
    super.notifyListeners();
  }

  /// 帧后复用暂停释放判定；暂停或 hydrate 未完成时继续等待。
  void _deferRelease() {
    if (_releasePending) return;
    _releasePending = true;
    SchedulerBinding.instance.addPostFrameCallback((_) {
      _releasePending = false;
      if (!isDisposed) _batch(_applyRelease);
    });
  }

  /// 测试用的当前运行时槽位数量，不包含 slots 配置。
  @visibleForTesting
  int get debugSlotCount => _slots.length;

  /// 查询 [id] 在 [cooldown] 下的资格；持久化读取未完成时 wait 为 null。
  OverlayCooldownStatus cooldownStatus(String id, OverlayCooldown cooldown) {
    if (!_cooldowns._hydrated && cooldown._needsPersistence) {
      return const OverlayCooldownStatus(
          canShow: false, permanentlyBlocked: false, wait: null);
    }
    final wait = _cooldowns.timeUntilEligible(id, cooldown, _now());
    return OverlayCooldownStatus(
        canShow: wait == Duration.zero,
        permanentlyBlocked: _cooldowns.permanentlyBlocked(id, cooldown),
        wait: wait);
  }

  /// 清除 [id] 的 session 与持久化计数并重调度；销毁后无操作。
  void resetCooldown(String id) => _resetCooldowns(id);

  /// 清除所有冷却计数并重调度；销毁后无操作。
  void clearCooldowns() => _resetCooldowns();

  /// 复用串行持久化写入，并给排队条目重新判定资格。
  void _resetCooldowns([String? id]) => _batch(() {
        if (isDisposed) return;
        _cooldowns.reset(id);
        if (!_paused) _applyRelease();
        _notify();
      });

  /// 移除包含 [tag] 的所有条目，先全部移除再推进，结束原因为 removed。
  void clearTag(String tag) =>
      clearWhere((record) => record.tags.contains(tag));

  /// Delay inserted between one overlay closing and the next one showing.
  final Duration gap;

  /// 各槽位的间隔与排队上限；未配置时使用全局默认值。
  final Map<String, OverlaySlotOptions> slots;

  /// 异步广播生命周期事件，没有监听者时不创建事件。
  final _events = StreamController<OverlayEvent>.broadcast();

  /// 入队、展示和首次结束事件；dispose 后关闭。
  Stream<OverlayEvent> get events => _events.stream;

  /// 仅在有监听者且管理器存活时发布事件。
  void _emit(_Entry e, OverlayEventType type, [OverlayEndReason? reason]) {
    if (!isDisposed && _events.hasListener) {
      _events.add(
          OverlayEvent(type: type, id: e.id, slot: e.slot, reason: reason));
    }
  }

  /// 尚未释放的独立暂停来源。
  final _holds = <OverlayHold>{};

  /// 当前独立暂停来源数量，不包含手动暂停和路由暂停。
  int get holdCount => _holds.length;

  /// 建立独立暂停来源；所有来源释放后才恢复，销毁后返回已释放对象。
  OverlayHold hold([Object? reason]) {
    return _batch(() {
      if (isDisposed) return OverlayHold._(reason, null);
      final before = _paused;
      late final OverlayHold token;
      token = OverlayHold._(
          reason,
          () => _batch(() {
                if (isDisposed) return;
                final before = _paused;
                _holds.remove(token);
                _applyPauseTransition(before);
                _notify();
              }));
      _holds.add(token);
      _applyPauseTransition(before);
      _notify();
      return token;
    });
  }

  /// 请求后端关闭后等待 dismissed 的时限；null 表示不限时，默认 10 秒。
  final Duration? dismissTimeout;

  /// resolve 默认等待时限；null 表示不限时，默认 30 秒。
  final Duration? resolveTimeout;

  final DateTime Function() _now;
  late final _CooldownStore _cooldowns;
  late final Future<void> _ready;

  final Map<String, _Slot> _slots = <String, _Slot>{};
  final List<_Entry> _overlaps = <_Entry>[];
  final List<_Entry> _pendingOverlaps = <_Entry>[];
  final Map<String, _Entry> _byId = <String, _Entry>{};
  final Map<String, Object?> _context = <String, Object?>{};
  int _seqCounter = 0;
  final List<Object> _pauseOnRoutes;

  /// Explicit [pauseAll]/[resumeAll] state — independent of [_routeZonePaused];
  /// the effective [_paused] is their OR, so leaving a route zone doesn't
  /// override a still-active manual pause, and vice versa.
  bool _manualPaused = false;

  /// True while `_context['route']` matches one of [_pauseOnRoutes] — kept in
  /// sync by [_updateRouteZone], called from every [setContext].
  bool _routeZonePaused = false;

  bool get _paused => _manualPaused || _routeZonePaused || _holds.isNotEmpty;

  /// Completes when persisted cooldown counters have been hydrated and the
  /// queue has been re-scheduled. Entries gated on persisted caps
  /// (`total`/`day`/`hour`/`minute`/`minGap`) wait for this automatically, so
  /// awaiting it before [open] is optional.
  Future<void> ready() => _ready;

  /// The `route` context key last set via [setContext] (`null` if never set).
  /// Typically kept in sync automatically by an `LayermanNavigatorObserver` —
  /// read this instead of maintaining a separate route mirror in the host.
  Object? get currentRoute => _context['route'];

  /// 是否因手动暂停、路由免打扰或未释放的 hold 而冻结；各来源按 OR 组合。
  bool get isPaused => _paused;

  /// 等待中的 id；各 slot 内按 replace、优先级、FIFO 的真实出场顺序返回。
  List<String> get queuedIds => <String>[
        for (final slot in _slots.values)
          for (final e in slot.queue) e.id,
        for (final e in _pendingOverlaps) e.id,
      ];

  /// 已展示的 id（仅 open/closing，不含 resolving），含串行与 overlap。
  List<String> get activeIds => <String>[
        for (final slot in _slots.values)
          if (slot.active != null && slot.active!.isShown) slot.active!.id,
        for (final e in _overlaps)
          if (e.isShown) e.id,
      ];

  /// 正在解析且占据槽位的 id，包含 overlap 中正在解析的条目。
  List<String> get resolvingIds => [
        for (final e in _byId.values)
          if (e.phase == _EntryPhase.resolving) e.id,
      ];

  /// 所有受管条目的快照；各 slot 内先当前条目，再按出场顺序列出队列。
  List<OverlayRecord> get records => [
        for (final s in _slots.values) ...[
          if (s.active != null) _record(s.active!),
          for (final e in s.queue) _record(e),
        ],
        for (final e in _overlaps) _record(e),
        for (final e in _pendingOverlaps) _record(e),
      ];

  /// 返回指定 id 的当前快照；未受管时返回 null。
  OverlayRecord? recordOf(String id) {
    final e = _byId[id];
    return e == null ? null : _record(e);
  }

  /// 将内部条目转换为只读状态快照。
  OverlayRecord _record(_Entry e) =>
      OverlayRecord._(e.id, e.slot, e.data, e.isActive, e.phase.name, e.tags);

  /// id 是否已展示（仅 open/closing，不含 resolving）。
  bool isShowing(String id) {
    final e = _byId[id];
    return e != null && e.isShown;
  }

  /// Unhooks [e] from `slot.active` / `_overlaps` / `_pendingOverlaps`
  /// tracking. Returns whether it was occupying its slot's serial `active`
  /// position (callers that need to advance the queue check this).
  bool _detachFromActive(_Entry e) {
    final s = _slots[e.slot];
    final wasActive = s != null && s.active == e;
    if (wasActive) s.active = null;
    _overlaps.remove(e);
    _pendingOverlaps.remove(e);
    return wasActive;
  }

  /// Merge [partial] into the condition context and re-evaluate:
  /// * shown overlays whose conditions no longer pass are auto-dismissed
  ///   (unless they opted out via `dismissWhenUnmet: false`);
  /// * queued overlays that became eligible get a chance to show.
  ///
  /// Reserved keys used by the built-in sugar: `route` (String) and `auth`
  /// (bool). Everything else is free-form for `when` predicates.
  void setContext(Map<String, Object?> partial) {
    return _batch(() {
      if (isDisposed) return;
      _context.addAll(partial);
      _contextView = null;
      _updateRouteZone();
      final shown = <_Entry>[
        for (final s in _slots.values)
          if (s.active != null) s.active!,
        ..._overlaps,
      ];
      for (final e in shown) {
        if (e.isActive && e.dismissWhenUnmet && !_conditionsPass(e)) {
          _remove(e, reason: OverlayEndReason.unmet);
        }
      }
      for (final slot in _slots.keys.toList()) {
        _schedule(slot);
      }
      _notify();
    });
  }

  /// Re-check `_context['route']` against [_pauseOnRoutes] and flip
  /// [_routeZonePaused] on entry/exit — freezing/releasing exactly like a
  /// manual [pauseAll]/[resumeAll], but composed with it via [_paused]'s OR so
  /// leaving the zone doesn't undo an unrelated manual pause.
  void _updateRouteZone() {
    if (_pauseOnRoutes.isEmpty) return;
    final current = _context['route'];
    final matches = _pauseOnRoutes.any((p) => _routeMatches(p, current));
    if (matches == _routeZonePaused) return;
    final before = _paused;
    _routeZonePaused = matches;
    _applyPauseTransition(before);
  }

  /// Freeze everything: no new activation (serial, overlap, replace) and all
  /// running `duration` timers pause. Explicit [close]/[remove]/[clear] still
  /// work. [resumeAll] releases held overlaps and re-schedules.
  void pauseAll() {
    return _batch(() {
      if (isDisposed) return;
      if (_manualPaused) return;
      final before = _paused;
      _manualPaused = true;
      _applyPauseTransition(before);
    });
  }

  /// Undo [pauseAll]: release overlaps held while paused (if still eligible),
  /// thaw `duration` timers and re-schedule every slot.
  void resumeAll() {
    return _batch(() {
      if (isDisposed) return;
      if (!_manualPaused) return;
      final before = _paused;
      _manualPaused = false;
      _applyPauseTransition(before);
    });
  }

  /// 手动、路由和 hold 共享的边沿触发器；仅有效暂停状态变化时冻结或恢复。
  void _applyPauseTransition(bool before) {
    final after = _paused;
    if (after == before) return;
    if (after) {
      _applyFreeze();
    } else {
      _applyRelease();
    }
  }

  void _applyFreeze() {
    for (final s in _slots.values) {
      _cancelCooldownTimer(s);
    }
    for (final e in _byId.values) {
      _freezeDuration(e);
    }
    _notify();
  }

  void _applyRelease() {
    if (_paused || isDisposed) return;
    if (_inBuildPhase) {
      _deferRelease();
      return;
    }
    final held = List<_Entry>.of(_pendingOverlaps);
    _pendingOverlaps.clear();
    for (final e in held) {
      if (!_isCurrent(e)) continue;
      if (_paused || _waitingForHydrate(e)) {
        _pendingOverlaps.add(e);
      } else if (_eligible(e)) {
        _openOverlap(e);
      } else {
        _byId.remove(e.id);
        _settle(e, null, _dropReason(e));
      }
    }
    for (final e in _byId.values.toList()) {
      if (!_paused && e.phase == _EntryPhase.resolving && e.hasHeldData) {
        e.hasHeldData = false;
        _open(e);
      }
    }
    for (final e in _byId.values) {
      _thawDuration(e);
    }
    for (final slot in _slots.keys.toList()) {
      _schedule(slot);
    }
    _notify();
  }

  /// Freeze [id]'s `duration` countdown (the overlay stays shown).
  void pause(String id) {
    return _batch(() {
      if (isDisposed) return;
      final e = _byId[id];
      if (e == null || e.paused) return;
      e.paused = true;
      _freezeDuration(e);
      _notify();
    });
  }

  /// Resume [id]'s `duration` countdown with the remaining time.
  void resume(String id) {
    return _batch(() {
      if (isDisposed) return;
      final e = _byId[id];
      if (e == null || !e.paused) return;
      e.paused = false;
      _thawDuration(e);
      _notify();
    });
  }

  /// Merge [patch] into [id]'s `data` in place (map-into-map merges shallowly,
  /// anything else replaces) and notify listeners — without any queue change.
  ///
  /// The manager doesn't re-render (it owns no widgets); a backend can listen
  /// to PresentContext.dataListenable for live data. PresentContext.data stays
  /// the snapshot captured when present was called.
  void update(String id, Object? patch) {
    return _batch(() {
      if (isDisposed) return;
      final e = _byId[id];
      if (e == null) return;
      final current = e.data;
      if (current is Map && patch is Map) {
        e.data = <Object?, Object?>{...current, ...patch};
      } else {
        e.data = patch;
      }
      _notify();
    });
  }

  /// Enqueue (or immediately show) an overlay, rendered through [present].
  ///
  /// Returns a [Future] that completes when the overlay closes: with the value
  /// the backend reported (via [PresentedOverlay.dismissed] or the `result`
  /// passed to [close]), or `null` when dismissed.
  ///
  /// [present] is the SOLE rendering hook (see [Present]/[PresentedOverlay]):
  /// invoked only when the queue grants this entry its slot, it shows the UI
  /// however it likes and returns a handle the manager awaits and can preempt.
  ///
  /// * [id] — unique key; if omitted an auto id is generated. Reusing an id
  ///   that is currently shown replaces it; reusing a queued id overrides it.
  /// * [tags] — copied, read-only labels for clearTag and record inspection.
  /// * [slot] — independent serial queue (default `''`).
  /// * [priority] — higher shows first; ties break FIFO.
  /// * [delay] — wait before this overlay appears (overrides [gap] for itself).
  /// * [duration] — auto-close this long after opening.
  /// * [expireAfter] — maximum serial queue wait; ignored for overlap.
  /// * [replace] — preempt the slot's current overlay, show immediately
  ///   (unless the current one is [affix]ed, or the replacer is not eligible).
  ///   The preempted overlay is closed (its result completes `null`); backends
  ///   cannot be faithfully re-presented, so there is no re-show.
  /// * [affix] — protect this overlay from `replace` (explicit [close]/
  ///   [remove]/[clear] still work; duplicate-id self-update is not blocked).
  /// * [overlap] — bypass the queue and stack on top immediately. Conditions/
  ///   cooldown act as a fire-gate: not eligible ⇒ dropped (result `null`).
  /// * [when]/[route]/[requiresAuth] — conditions against [setContext]
  ///   (`when` overrides the sugar); [dismissWhenUnmet] (default true)
  ///   auto-dismisses a shown overlay whose conditions stop holding.
  /// * [cooldown] — frequency caps; counts on real open. Keyed by [id], so an
  ///   explicit [id] is required (asserted in debug).
  /// * [resolve] — backend-driven payload: called when the entry is granted
  ///   the slot; `null` skips the overlay, otherwise the value becomes `data`.
  /// * [resolveTimeout] — null inherits the constructor default; zero disables
  ///   the timeout for this entry. Timeout skips without counting cooldown.
  /// * [beforeClose] — close guard: returning `false` cancels a [close].
  /// * [exitDuration] — extra grace between the backend's `dismissed` signal
  ///   and the queue advancing (lets a shared exit animation finish); null
  ///   advances immediately.
  Future<T?> open<T>({
    required Present<T> present,
    String? id,
    Object? data,
    Set<String>? tags,
    String slot = '',
    int priority = 0,
    Duration? delay,
    Duration? duration,
    Duration? expireAfter,
    bool replace = false,
    bool affix = false,
    bool overlap = false,
    OverlayPredicate? when,
    Object? route,
    bool? requiresAuth,
    bool dismissWhenUnmet = true,
    OverlayCooldown? cooldown,
    Future<T?> Function()? resolve,
    Duration? resolveTimeout,
    FutureOr<bool> Function()? beforeClose,
    Duration? exitDuration,
  }) =>
      submit<T>(
        present: present,
        id: id,
        data: data,
        tags: tags,
        slot: slot,
        priority: priority,
        delay: delay,
        duration: duration,
        expireAfter: expireAfter,
        replace: replace,
        affix: affix,
        overlap: overlap,
        when: when,
        route: route,
        requiresAuth: requiresAuth,
        dismissWhenUnmet: dismissWhenUnmet,
        cooldown: cooldown,
        resolve: resolve,
        resolveTimeout: resolveTimeout,
        beforeClose: beforeClose,
        exitDuration: exitDuration,
      ).result;

  /// 提交条目并返回类型化票据；参数与 open 相同。
  /// expireAfter 仅计算激活前的串行排队时间，overlap 不适用。
  /// tags 默认空集合，提交时复制，之后通过 recordOf 或 records 只读查询。
  OverlayTicket<T> submit<T>({
    required Present<T> present,
    String? id,
    Object? data,
    Set<String>? tags,
    String slot = '',
    int priority = 0,
    Duration? delay,
    Duration? duration,
    Duration? expireAfter,
    bool replace = false,
    bool affix = false,
    bool overlap = false,
    OverlayPredicate? when,
    Object? route,
    bool? requiresAuth,
    bool dismissWhenUnmet = true,
    OverlayCooldown? cooldown,
    Future<T?> Function()? resolve,
    Duration? resolveTimeout,
    FutureOr<bool> Function()? beforeClose,
    Duration? exitDuration,
  }) {
    return _batch(() {
      assert(!isDisposed, 'Cannot open an overlay after Layerman.dispose().');
      assert(
        cooldown == null || id != null,
        'cooldown is keyed by id: pass an explicit id. An auto-generated id '
        'changes on every open, so the cap would never apply.',
      );
      assert(
        route == null || _isRoutePattern(route),
        'route must be a String, List<String> or RegExp',
      );
      final resolvedId = id ?? 'overlay:${++_seqCounter}';
      final completer = Completer<T?>();
      final outcome = Completer<OverlayOutcome<T>>();
      late final _Entry entry;
      entry = _Entry(
        id: resolvedId,
        tags: Set<String>.unmodifiable(tags ?? const <String>{}),
        slot: slot,
        priority: priority,
        seq: ++_seqCounter,
        replace: replace,
        affix: affix,
        delay: delay,
        duration: duration,
        exitDuration: exitDuration,
        when: when,
        route: route,
        requiresAuth: requiresAuth,
        dismissWhenUnmet: dismissWhenUnmet,
        cooldown: cooldown,
        beforeClose: beforeClose,
        resolveData: resolve == null ? null : () async => await resolve(),
        resolveTimeout: resolveTimeout == Duration.zero
            ? null
            : (resolveTimeout ?? this.resolveTimeout),
        acceptsResult: (Object? r) => r is T?,
        settle: (Object? r) {
          if (!completer.isCompleted) completer.complete(r as T?);
        },
        settleOutcome: (r, reason) {
          outcome.complete(OverlayOutcome<T>(r as T?, reason));
        },
        data: data,
        presentBackend: () {
          final presented = present(
            PresentContext._(resolvedId, slot, entry.data, entry.dataNotifier),
          );
          final dismiss = presented.dismiss;
          entry.externalDismiss =
              dismiss == null ? null : (Object? r) => dismiss(r as T?);
          presented.dismissed.then(
            (T? r) => _onExternalDismissed(entry, r),
            onError: (Object _) => _onExternalDismissed(entry, null),
          );
        },
      );

      final ticket =
          OverlayTicket<T>._(this, entry, completer.future, outcome.future);
      if (isDisposed) {
        _settle(entry, null, OverlayEndReason.disposed);
        return ticket;
      }

      // Handle id reuse.
      final existing = _byId[resolvedId];
      String? freedSlot; // serial slot the replaced entry vacated
      if (existing != null) {
        if (existing.isActive) {
          // Replaced in place; old result -> null.
          if (_discardActive(existing, OverlayEndReason.superseded)) {
            freedSlot = existing.slot;
          }
          entry.skipGap = true;
        } else {
          _removeFromQueue(existing);
          _pendingOverlaps.remove(existing);
          _byId.remove(existing.id);
          _settle(existing, null, OverlayEndReason.superseded);
        }
      }
      _byId[resolvedId] = entry;
      _emit(entry, OverlayEventType.queued);

      // The replaced entry's old slot must not stall if the new one lives elsewhere.
      void rescheduleFreed() {
        if (freedSlot != null && (overlap || freedSlot != slot)) {
          _schedule(freedSlot);
        }
      }

      if (overlap) {
        // Conditions/cooldown are a one-shot fire-gate for overlaps (TS rule:
        // "now or never") — but a paused manager holds them for resumeAll.
        final conditionsPass = _conditionsPass(entry);
        final waitingForHydrate = conditionsPass && _waitingForHydrate(entry);
        if (!conditionsPass || (!waitingForHydrate && !_cooldownPass(entry))) {
          _byId.remove(entry.id);
          _settle(entry, null, _dropReason(entry));
        } else if (_paused || waitingForHydrate || _inBuildPhase) {
          _pendingOverlaps.add(entry);
          if (_inBuildPhase) _deferRelease();
        } else {
          _openOverlap(entry);
        }
        rescheduleFreed();
        _notify();
        return ticket;
      }

      final s = _slotFor(slot);
      // A replace only preempts the current overlay when the replacer itself is
      // eligible right now (TS invariant 5b) and the manager is not paused; an
      // affixed current blocks preemption but the replacer keeps its front-band
      // ordering and shows next.
      if (replace && !_paused && _eligible(entry)) {
        entry.skipGap = true;
        final cur = s.active;
        if (cur != null && cur.isActive && !cur.affix) {
          // A backend that's been dismissed can't be faithfully re-presented
          // (that would re-run its side effects), so the preempted overlay is
          // discarded (closed + result `null`), never re-queued.
          _discardActive(cur, OverlayEndReason.replaced);
        }
        // TS-parity: a replace arriving during the transition gap (or appear
        // delay) means "show me NOW" — skip the remaining gap / delay.
        if (s.gapPending) {
          s.gapTimer?.cancel();
          s.gapTimer = null;
          s.gapPending = false;
        }
        if (s.delayTimer != null) {
          s.delayTimer!.cancel();
          s.delayTimer = null;
        }
      }
      _enqueue(s, entry);
      if (expireAfter != null) {
        entry.queueTimer = Timer(
            expireAfter,
            () => _batch(() {
                  if (!_isCurrent(entry) ||
                      entry.phase != _EntryPhase.pending) {
                    return;
                  }
                  _remove(entry, reason: OverlayEndReason.queueExpired);
                  _schedule(slot);
                }));
      }
      final maxQueued = slots[slot]?.maxQueued;
      if (maxQueued != null && s.queue.length > maxQueued) {
        _remove(s.queue.last, reason: OverlayEndReason.queueFull);
      }
      if (_inBuildPhase &&
          _isCurrent(entry) &&
          freedSlot == slot &&
          !_paused &&
          _eligible(entry)) {
        s.takeover = entry;
      }
      if (_isCurrent(entry) &&
          !_inBuildPhase &&
          freedSlot == slot &&
          !overlap &&
          !_paused &&
          _eligible(entry)) {
        _activate(entry);
      } else {
        _schedule(slot);
      }
      rescheduleFreed();
      _notify();
      return ticket;
    });
  }

  /// Two-phase close [id], optionally delivering [result]. A `beforeClose`
  /// guard returning `false` cancels the close; while an async guard is still
  /// pending, further `close`/`dismiss` calls for the same id are ignored.
  ///
  /// Throws an [ArgumentError] (leaving the overlay untouched) if [result] is
  /// not a valid `T?` for the `open<T>()` that created this overlay.
  void close(String id, [Object? result]) {
    return _batch(() {
      if (isDisposed) return;
      final e = _byId[id];
      if (e == null) return;
      if (e.closeGuardPending) return;
      if (!e.acceptsResult(result)) {
        throw ArgumentError.value(
            result, 'result', 'Invalid result type for overlay "$id"');
      }
      _close(e, result);
    });
  }

  /// Dismiss [id] (close with a `null` result).
  void dismiss(String id) => close(id);

  /// Immediately remove [id] with no exit grace (settles `null` if it had
  /// not been settled by a prior [close]). Bypasses `beforeClose`.
  void remove(String id) {
    return _batch(() {
      if (isDisposed) return;
      final e = _byId[id];
      if (e == null) return;
      _remove(e);
    });
  }

  /// Remove everything: queued and active, across all slots and overlaps.
  /// Unsettled results resolve `null`. Bypasses `beforeClose`.
  void clear() => _clear(OverlayEndReason.removed);

  /// 按指定原因清空所有条目，同时取消槽位和条目计时器。
  void _clear(OverlayEndReason reason) {
    return _batch(() {
      if (isDisposed) return;
      for (final s in _slots.values) {
        _cancelCooldownTimer(s);
        s.gapTimer?.cancel();
        s.gapTimer = null;
        s.gapPending = false;
        s.delayTimer?.cancel();
        s.delayTimer = null;
      }
      final all = _byId.values.toList();
      for (final e in all) {
        _remove(e, advance: false, reason: reason);
      }
      _notify();
    });
  }

  /// Selectively remove every entry (queued or shown) matching [test].
  /// "Close all of group X" is `clearWhere((r) => (r.data as MyData?)?.group == 'x')`.
  void clearWhere(bool Function(OverlayRecord record) test) {
    return _batch(() {
      if (isDisposed) return;
      final selected = <_Entry>[
        for (final e in _byId.values.toList())
          if (test(_record(e))) e,
      ];
      // Remove everything first and advance afterwards, so a matching queued
      // entry is never briefly activated just to be removed next.
      final freed = <String>{};
      for (final e in selected) {
        if (_remove(e, advance: false)) freed.add(e.slot);
      }
      freed.forEach(_advanceSlot);
    });
  }

  // ── internals ──────────────────────────────────────────────────────────

  _Slot _slotFor(String slot) => _slots.putIfAbsent(slot, () => _Slot());

  void _removeFromQueue(_Entry e) {
    final s = _slots[e.slot];
    s?.queue.remove(e);
    if (s?.takeover == e) s?.takeover = null;
  }

  /// 按固定排序键二分插入，维持真实出场顺序。
  void _enqueue(_Slot s, _Entry e) {
    var low = 0;
    var high = s.queue.length;
    while (low < high) {
      final mid = (low + high) ~/ 2;
      if (_cmp(s.queue[mid], e) <= 0) {
        low = mid + 1;
      } else {
        high = mid;
      }
    }
    s.queue.insert(low, e);
  }

  int _cmp(_Entry a, _Entry b) {
    // Replace entries form a front band: a preemptor must show before anything
    // that was already waiting (mirrors the TS package's replace-jumped rule),
    // e.g. when an affixed current blocked immediate preemption and the
    // replacer had to queue.
    if (a.replace != b.replace) return a.replace ? -1 : 1;
    if (a.priority != b.priority) return b.priority - a.priority;
    return a.seq - b.seq;
  }

  /// 缓存本次上下文的不可修改快照，供所有 when 共用。
  Map<String, Object?>? _contextView;

  bool _eligible(_Entry e) => _conditionsPass(e) && _cooldownPass(e);

  bool _conditionsPass(_Entry e) {
    final when = e.when;
    if (when != null) {
      try {
        return when(
            _contextView ??= Map<String, Object?>.unmodifiable(_context));
      } catch (error, stack) {
        if (!e.conditionErrorReported) {
          e.conditionErrorReported = true;
          _reportError(
              error, stack, 'while evaluating when for overlay "${e.id}"');
        }
        return false;
      }
    }
    if (e.route != null && !_routeMatches(e.route!, _context['route'])) {
      return false;
    }
    if (e.requiresAuth != null &&
        e.requiresAuth != (_context['auth'] == true)) {
      return false;
    }
    return true;
  }

  static bool _routeMatches(Object pattern, Object? current) {
    if (current is! String) return false;
    if (pattern is String) return pattern == current;
    if (pattern is List<String>) return pattern.contains(current);
    if (pattern is RegExp) return pattern.hasMatch(current);
    return false;
  }

  static bool _isRoutePattern(Object o) =>
      o is String || o is List<String> || o is RegExp;

  /// 持久化上限必须等待读取结束才能判定。
  bool _waitingForHydrate(_Entry e) =>
      !_cooldowns._hydrated && (e.cooldown?._needsPersistence ?? false);

  /// overlap 无法出场时，永久上限优先报告为 capped。
  OverlayEndReason _dropReason(_Entry e) =>
      e.cooldown != null && _cooldowns.permanentlyBlocked(e.id, e.cooldown!)
          ? OverlayEndReason.capped
          : OverlayEndReason.dropped;

  bool _cooldownPass(_Entry e) {
    final cd = e.cooldown;
    if (cd == null) return true;
    return _cooldowns.canShow(e.id, cd, _now());
  }

  void _cancelCooldownTimer(_Slot s) {
    s.cooldownTimer?.cancel();
    s.cooldownTimer = null;
  }

  void _schedule(String slot) {
    if (isDisposed) return;
    if (_inBuildPhase) {
      if (_deferredSlots.add(slot)) {
        SchedulerBinding.instance.addPostFrameCallback((_) {
          _deferredSlots.remove(slot);
          if (!isDisposed) _batch(() => _schedule(slot));
        });
      }
      return;
    }
    if (_paused) return;
    final s = _slotFor(slot);
    _cancelCooldownTimer(s);
    if (s.active != null) return; // slot occupied
    if (s.gapPending) return; // waiting out the transition gap
    if (s.delayTimer != null) {
      return; // waiting out the per-overlay appear delay
    }
    if (s.queue.isEmpty) return;

    final takeover = s.takeover;
    s.takeover = null;
    _Entry? front = takeover != null &&
            _isCurrent(takeover) &&
            s.queue.contains(takeover) &&
            _eligible(takeover)
        ? takeover
        : null;
    for (var i = 0; i < s.queue.length;) {
      if (front != null) break;
      final e = s.queue[i];
      final cd = e.cooldown;
      if (cd != null && _cooldowns.permanentlyBlocked(e.id, cd)) {
        s.queue.removeAt(i);
        if (_isCurrent(e)) _byId.remove(e.id);
        _settle(e, null, OverlayEndReason.capped);
        _notify();
        if (_paused ||
            s.active != null ||
            s.gapPending ||
            s.delayTimer != null) {
          return;
        }
        continue;
      }
      i++;
      if (_eligible(e)) {
        front = e;
        break;
      }
    }
    if (front == null) {
      // Nothing eligible now. Entries blocked purely by a time-based cooldown
      // (minGap / bucket rollover) have a known expiry — wake the slot then so
      // they don't wait in the queue forever (cooldown expiry is otherwise not
      // a scheduling trigger).
      _armCooldownWake(slot, s);
      return; // ineligible entries WAIT
    }

    // Per-overlay appear delay.
    if (!front.skipGap &&
        !front.delayConsumed &&
        front.delay != null &&
        front.delay! > Duration.zero) {
      front.delayConsumed = true;
      s.delayTimer?.cancel();
      s.delayTimer = Timer(
          front.delay!,
          () => _batch(() {
                s.delayTimer = null;
                _schedule(slot);
              }));
      return;
    }
    _activate(front);
  }

  /// Arm a one-shot timer to re-run [_schedule] when the soonest time-based
  /// cooldown among the slot's otherwise-eligible queued entries expires.
  void _armCooldownWake(String slot, _Slot s) {
    Duration? soonest;
    for (final e in s.queue) {
      final cd = e.cooldown;
      if (cd == null) continue;
      if (!_conditionsPass(e)) {
        continue; // conditions are event-driven, not timed
      }
      final w = _cooldowns.timeUntilEligible(e.id, cd, _now());
      if (w == null || w <= Duration.zero) continue;
      if (soonest == null || w < soonest) soonest = w;
    }
    if (soonest == null) return;
    // Small cushion so the timer fires strictly after the cap has cleared.
    s.cooldownTimer = Timer(
        soonest + const Duration(milliseconds: 16),
        () => _batch(() {
              s.cooldownTimer = null;
              _schedule(slot);
              _notify();
            }));
  }

  void _activate(_Entry e) {
    final s = _slotFor(e.slot);
    e.queueTimer?.cancel();
    e.queueTimer = null;
    _removeFromQueue(e);
    s.active = e;
    _begin(e);
  }

  /// Resolve (if the entry has a `resolve`) and then open [e].
  void _begin(_Entry e) {
    final resolver = e.resolveData;
    if (resolver != null) {
      // Backend-driven payload: the slot is committed while resolving (not
      // interrupted by later arrivals); null ⇒ skip without opening.
      e.phase = _EntryPhase.resolving;
      final timeout = e.resolveTimeout;
      if (timeout != null) {
        e.resolveTimer = Timer(
            timeout,
            () => _batch(() {
                  if (!_isCurrent(e) || e.phase != _EntryPhase.resolving) {
                    return;
                  }
                  _reportError(
                      TimeoutException(
                          'resolve "${e.id}" 等待 $timeout', timeout),
                      StackTrace.current,
                      'while resolving overlay "${e.id}"');
                  _onResolved(e, null);
                }));
      }
      _notify();
      resolver().then(
        (data) => _onResolved(e, data),
        onError: (Object _) => _onResolved(e, null),
      );
      return;
    }
    _open(e);
  }

  void _onResolved(_Entry e, Object? data) {
    return _batch(() {
      if (!_isCurrent(e) || e.phase != _EntryPhase.resolving) return;
      e.resolveTimer?.cancel();
      e.resolveTimer = null;
      if (data == null) {
        // Backend said "don't show": skip without counting cooldown.
        final wasSerial = _detachFromActive(e);
        _byId.remove(e.id);
        _settle(e, null, OverlayEndReason.skipped);
        _notify();
        if (wasSerial) _schedule(e.slot);
        return;
      }
      e.data = data;
      if (_paused || _inBuildPhase) {
        if (_inBuildPhase) _deferRelease();
        // No new activation while frozen: park the payload; [_applyRelease]
        // opens it without re-running the resolver.
        e.hasHeldData = true;
        _notify();
        return;
      }
      _open(e);
    });
  }

  void _open(_Entry e) {
    e.phase = _EntryPhase.open;
    try {
      e.presentBackend();
    } catch (error, stack) {
      // A throwing backend must not wedge the slot: report, drop the entry
      // (result null, no cooldown counted) and let the queue move on.
      _reportError(error, stack, 'while presenting overlay "${e.id}"');
      _remove(e, reason: OverlayEndReason.failed);
      return;
    }
    _emit(e, OverlayEventType.shown);
    final cd = e.cooldown;
    if (cd != null) _cooldowns.record(e.id, cd, _now());
    _startDuration(e);
    _notify();
  }

  void _openOverlap(_Entry e) {
    _overlaps.add(e);
    _begin(e);
  }

  /// Duration expiry: an automatic teardown, so it bypasses `beforeClose`
  /// (which gates only an explicit [close]).
  void _autoClose(_Entry e) {
    return _batch(() {
      if (_isCurrent(e) && _closable(e)) {
        _doClose(e, null, OverlayEndReason.expired);
      }
    });
  }

  void _startDuration(_Entry e) {
    // A paused/frozen entry carries its REMAINING time (see [_freezeDuration]);
    // a fresh open uses the full `duration`.
    final d = e.durationRemaining ?? e.duration;
    if (d == null) {
      e.durationRemaining = null;
      return;
    }
    if (_paused || e.paused) {
      e.durationRemaining = d; // already d if this was a resume; harmless if so
      return;
    }
    e.durationRemaining = null;
    e.durationDeadline = _now().add(d);
    e.durationTimer = Timer(d, () => _autoClose(e));
  }

  void _freezeDuration(_Entry e) {
    final timer = e.durationTimer;
    if (timer == null) return;
    timer.cancel();
    e.durationTimer = null;
    final deadline = e.durationDeadline;
    var remaining =
        deadline == null ? Duration.zero : deadline.difference(_now());
    if (remaining < Duration.zero) remaining = Duration.zero;
    e.durationRemaining = remaining;
  }

  void _thawDuration(_Entry e) {
    if (_paused || e.paused) return;
    final remaining = e.durationRemaining;
    if (remaining == null || e.phase != _EntryPhase.open) return;
    e.durationRemaining = null;
    e.durationDeadline = _now().add(remaining);
    e.durationTimer = Timer(remaining, () => _autoClose(e));
  }

  /// Whether [e] is still the live, tracked entry for its id — false once it's
  /// been removed/replaced-in-place (a stale async callback from an entry no
  /// longer in `_byId` must not act on it).
  bool _isCurrent(_Entry e) => _byId[e.id] == e;

  /// Whether [e] can still be meaningfully closed (actually shown).
  bool _closable(_Entry e) => e.phase == _EntryPhase.open;

  void _close(_Entry e, Object? result) {
    if (!_closable(e) || e.closeGuardPending) return;

    final guard = e.beforeClose;
    if (guard == null) {
      _doClose(e, result);
      return;
    }
    final FutureOr<bool> verdict;
    try {
      verdict = guard();
    } catch (_) {
      return; // a throwing guard cancels the close
    }
    if (verdict is bool) {
      if (verdict) _doClose(e, result);
      return;
    }
    e.closeGuardPending = true;
    verdict.then(
      (ok) => _batch(() {
        e.closeGuardPending = false;
        // Re-check current state at resolution time — the entry may have been
        // removed/replaced while the guard was pending.
        if (ok && _isCurrent(e) && _closable(e)) _doClose(e, result);
      }),
      onError: (Object _) => _batch(() {
        e.closeGuardPending = false;
        // A failing guard cancels the close.
      }),
    );
  }

  void _doClose(_Entry e, Object? result,
      [OverlayEndReason reason = OverlayEndReason.closed]) {
    e.durationTimer?.cancel();
    e.durationTimer = null;
    e.durationRemaining = null;
    _settle(e, result, reason);
    e.phase = _EntryPhase.closing;
    _notify();
    if (!_isCurrent(e)) return; // a listener removed/replaced it meanwhile
    if (e.externalDismiss == null || e.externalDone) {
      // Backend already closed, or cannot be closed by us: just detach.
      _remove(e);
    } else if (!_callDismiss(e, result)) {
      // Graceful backend close is driven by its dismissed signal
      // (+ optional exitDuration) in _onExternalDismissed; if the backend
      // failed to even start closing, don't wait forever.
      _remove(e);
    } else if (_isCurrent(e) && !e.externalDone && dismissTimeout != null) {
      final timeout = dismissTimeout!;
      e.dismissTimer = Timer(
          timeout,
          () => _batch(() {
                if (!_isCurrent(e) || e.externalDone) return;
                _reportError(
                    TimeoutException('dismiss "${e.id}" 等待 $timeout', timeout),
                    StackTrace.current,
                    'while awaiting dismissed for overlay "${e.id}"');
                _remove(e);
              }));
    }
  }

  /// The backend reported it is fully closed (user tap, barrier, back button,
  /// timeout, or our own dismiss). Settle and advance the queue.
  void _onExternalDismissed(_Entry e, Object? result) {
    return _batch(() {
      e.externalDone = true;
      e.dismissTimer?.cancel();
      e.dismissTimer = null;
      _settle(e, result, OverlayEndReason.dismissedByBackend);
      if (!_isCurrent(e)) return; // already removed / replaced in place
      if (e.phase == _EntryPhase.open) {
        // Closed directly by the backend (not via our close()).
        e.phase = _EntryPhase.closing;
        _notify();
      }
      final grace = e.exitDuration;
      if (grace != null && grace > Duration.zero) {
        e.removeTimer?.cancel();
        e.removeTimer = Timer(grace, () => _batch(() => _remove(e)));
      } else {
        _remove(e);
      }
    });
  }

  /// Remove an active/queued entry from the world. When [advance] is true and
  /// it occupied a serial slot, the queue is advanced (after [gap]).
  /// Returns whether [e] occupied its slot's serial `active` position.
  bool _remove(_Entry e,
      {bool advance = true,
      OverlayEndReason reason = OverlayEndReason.removed}) {
    e.cancelTimeouts();
    e.durationTimer?.cancel();
    e.removeTimer?.cancel();
    e.durationTimer = null;
    e.removeTimer = null;

    // Only unregister the id if it still maps to [e] — a listener may have
    // reopened the same id while [e] was closing.
    if (_isCurrent(e)) _byId.remove(e.id);
    _dismissBackendBestEffort(e);

    final wasSerialActive = _detachFromActive(e);
    _removeFromQueue(e);

    _settle(e, null, reason);

    if (advance && wasSerialActive) _advanceSlot(e.slot);
    _notify();
    return wasSerialActive;
  }

  /// A serial slot just freed up: schedule the next entry (after [gap]).
  void _advanceSlot(String slot) {
    final s = _slotFor(slot);
    final slotGap = slots[slot]?.gap ?? gap;
    if (slotGap > Duration.zero) {
      s.gapPending = true;
      s.gapTimer?.cancel();
      s.gapTimer = Timer(
          slotGap,
          () => _batch(() {
                s.gapPending = false;
                s.gapTimer = null;
                _schedule(slot);
                _notify();
              }));
    } else {
      _schedule(slot);
    }
  }

  /// 抢占时先分离旧条目，不推进槽位；由提交方完成入队并统一通知。
  /// 返回旧条目是否占据串行 active 位置。
  bool _discardActive(_Entry e, OverlayEndReason reason) {
    e.cancelTimeouts();
    e.durationTimer?.cancel();
    e.removeTimer?.cancel();
    if (_isCurrent(e)) _byId.remove(e.id);
    _dismissBackendBestEffort(e);
    final wasSerialActive = _detachFromActive(e);
    _settle(e, null, reason);
    return wasSerialActive;
  }

  /// When an entry leaves the queue while its backend may still be showing
  /// (replace/clear/remove), ask the backend to close, fire-and-forget.
  void _dismissBackendBestEffort(_Entry e) {
    if (e.externalDone) return;
    e.externalDone = true; // its dismissed signal must not re-drive removal
    if (e.externalDismiss != null) _callDismiss(e, null);
  }

  /// Ask the backend to close [e]; a sync throw or async failure is reported,
  /// never propagated. Returns false only on a synchronous failure.
  bool _callDismiss(_Entry e, Object? result) {
    if (e.dismissRequested) return true; // 已经请求过：不再重复调用后端
    e.dismissRequested = true;
    try {
      e.externalDismiss!(result).catchError((Object error, StackTrace stack) {
        _reportError(error, stack, 'while dismissing overlay "${e.id}"');
      });
      return true;
    } catch (error, stack) {
      _reportError(error, stack, 'while dismissing overlay "${e.id}"');
      e.externalDone = true; // don't ask a broken backend a second time
      return false;
    }
  }

  void _settle(_Entry e, Object? result, OverlayEndReason reason) {
    if (e.settled) return;
    e.settled = true;
    e.cancelTimeouts();
    e.endReason ??= reason;
    try {
      e.settle(result);
    } catch (error, stack) {
      _reportError(error, stack, 'while settling overlay "${e.id}"');
      result = null;
      e.settle(null);
    }
    e.settleOutcome(result, e.endReason!);
    _emit(e, OverlayEventType.ended, e.endReason);
  }

  @override
  void dispose() {
    if (isDisposed) return;
    for (final s in _slots.values) {
      s.gapTimer?.cancel();
      s.delayTimer?.cancel();
      s.cooldownTimer?.cancel();
    }
    _clear(OverlayEndReason.disposed);
    _disposed = true;
    _deferredSlots.clear();
    _releasePending = false;
    _frameNotifyPending = false;
    _notifyPending = false;
    for (final token in _holds) {
      token._release = null;
    }
    _holds.clear();
    _events.close();
    super.dispose();
  }

  bool _disposed = false;

  /// Whether [dispose] has been called. Lets a deferred callback (e.g.
  /// `LayermanNavigatorObserver`'s post-frame `setContext`) check it's not
  /// about to call into a manager that was torn down in the meantime.
  bool get isDisposed => _disposed;
}
