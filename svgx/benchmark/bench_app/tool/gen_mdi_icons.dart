// One-off offline generator: extracts the first 1000 static-icon SVG strings
// (declaration order, deterministic) from iconify_flutter's bundled `Mdi`
// icon set and bakes them into lib/mdi_icons_1000.dart as a plain const list.
//
// Why bake instead of reading `Mdi.xxx` fields directly at benchmark runtime:
// Dart has no reflection in Flutter apps, so there's no way to enumerate
// `Mdi`'s ~13k static const fields by index without listing 1000 names by
// hand. Regenerating this file only needs to happen if iconify_flutter's
// pinned version changes.
//
// 一次性离线生成器：从 iconify_flutter 内置的 `Mdi` 图标集中按声明顺序（确定性）
// 提取前 1000 个静态图标 SVG 字符串，烘焙进 lib/mdi_icons_1000.dart 的普通
// const 列表。之所以烘焙而非运行时直接读 `Mdi.xxx`：Flutter 里 Dart 没有反射，
// 没法不手写 1000 个字段名就按下标枚举 `Mdi` 的近 1.3 万个 static const 字段。
// 只有 iconify_flutter 锁定版本变化时才需要重跑这个脚本。
//
// Run: dart run tool/gen_mdi_icons.dart
import 'dart:io';

final _fieldPattern = RegExp(
  r"static const String (\w+) =\s*'((?:[^'\\]|\\.)*)';",
  dotAll: true,
);

void main() {
  final pubCache =
      Platform.environment['PUB_CACHE'] ??
      '${Platform.environment['LOCALAPPDATA']}\\Pub\\Cache';
  final dir =
      Directory('$pubCache\\hosted\\pub.dev')
          .listSync()
          .whereType<Directory>()
          .map((d) => d.path.split(Platform.pathSeparator).last)
          .where((name) => name.startsWith('iconify_flutter-'))
          .toList()
        ..sort();
  if (dir.isEmpty) {
    stderr.writeln('iconify_flutter not found in pub cache');
    exit(1);
  }
  final mdiFile = File(
    '$pubCache\\hosted\\pub.dev\\${dir.last}\\lib\\icons\\mdi.dart',
  );
  final source = mdiFile.readAsStringSync();
  final matches = _fieldPattern.allMatches(source).take(1000).toList();
  if (matches.length < 1000) {
    stderr.writeln('Only found ${matches.length} icons, expected >= 1000');
    exit(1);
  }

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/gen_mdi_icons.dart. Do not edit by hand.')
    ..writeln('// 由 tool/gen_mdi_icons.dart 生成，请勿手改。')
    ..writeln('//')
    ..writeln('// The first 1000 static-icon SVGs (declaration order) from')
    ..writeln("// iconify_flutter's `Mdi` icon set (Material Design Icons),")
    ..writeln('// used as real-world icon data for the svgx-vs-flutter_svg')
    ..writeln('// benchmark.')
    ..writeln('const List<String> mdiIcons1000 = <String>[');
  for (final m in matches) {
    buffer.writeln("  '${m.group(2)}',");
  }
  buffer.writeln('];');

  File('lib/mdi_icons_1000.dart').writeAsStringSync(buffer.toString());
  stderr.writeln('Wrote ${matches.length} icons to lib/mdi_icons_1000.dart');
}
