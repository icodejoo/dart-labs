// One-off offline generator: extracts every real SMIL-animated icon SVG
// string (declaration order, deterministic) from iconify_flutter's bundled
// `LineMd` and `EosIcons` sets — the two Iconify collections CLAUDE.md
// already confirmed (via direct grep of the upstream `icon-sets` JSON) are
// 100% SMIL `<animate>`/`<animateTransform>`, 0% CSS — and bakes them into
// lib/anim_icons_real.dart as a plain const list, for the "1000 concurrently
// scrolling animated icons, real FPS" benchmark.
//
// Why bake instead of reading fields directly at runtime: same reason as
// tool/gen_mdi_icons.dart — no reflection, so no way to enumerate hundreds of
// static const fields without listing names by hand.
//
// 一次性离线生成器：从 iconify_flutter 内置的 `LineMd`/`EosIcons` 图标集中
// 按声明顺序提取全部真实 SMIL 动画图标 SVG 字符串（这两个集合已在 CLAUDE.md
// 里核实过 100% 是 SMIL、0% CSS），烘焙进 lib/anim_icons_real.dart 的普通
// const 列表，供"1000 个并发滚动动画图标，真实 FPS"基准使用。
//
// Run: dart run tool/gen_anim_icons.dart
import 'dart:io';

final _fieldPattern = RegExp(
  r"static const String (\w+) =\s*'((?:[^'\\]|\\.)*)';",
  dotAll: true,
);

void main() {
  final pubCache = Platform.environment['PUB_CACHE'] ??
      '${Platform.environment['LOCALAPPDATA']}\\Pub\\Cache';
  final dir = Directory('$pubCache\\hosted\\pub.dev')
      .listSync()
      .whereType<Directory>()
      .map((d) => d.path.split(Platform.pathSeparator).last)
      .where((name) => name.startsWith('iconify_flutter-'))
      .toList()
    ..sort();
  if (dir.isEmpty) {
    stderr.writeln('iconify_flutter not found in pub cache');
    exit(1);
  }
  final pkgDir = '$pubCache\\hosted\\pub.dev\\${dir.last}';
  final icons = <String>[];
  for (final file in ['lib/icons/line_md.dart', 'lib/icons/eos_icons.dart']) {
    final source = File('$pkgDir\\${file.replaceAll('/', '\\')}').readAsStringSync();
    final matches = _fieldPattern.allMatches(source);
    // Only keep icons that actually carry a SMIL animation tag — a handful of
    // fields in these sets are static companion glyphs.
    // 只保留真正带 SMIL 动画标签的图标——这两个集合里也混有少量静态伴生图形。
    for (final m in matches) {
      final svg = m.group(2)!;
      if (svg.contains('<animate')) icons.add(svg);
    }
  }
  if (icons.isEmpty) {
    stderr.writeln('No animated icons found');
    exit(1);
  }

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/gen_anim_icons.dart. Do not edit by hand.')
    ..writeln('// 由 tool/gen_anim_icons.dart 生成，请勿手改。')
    ..writeln('//')
    ..writeln('// Every real SMIL-animated SVG (declaration order) from')
    ..writeln("// iconify_flutter's `LineMd` + `EosIcons` sets, used as")
    ..writeln('// real-world animated-icon data for the 1000-icon scrolling')
    ..writeln('// FPS benchmark.')
    ..writeln('const List<String> animIconsReal = <String>[');
  for (final svg in icons) {
    buffer.writeln("  '$svg',");
  }
  buffer.writeln('];');

  File('lib/anim_icons_real.dart').writeAsStringSync(buffer.toString());
  stderr.writeln('Wrote ${icons.length} animated icons to lib/anim_icons_real.dart');
}
